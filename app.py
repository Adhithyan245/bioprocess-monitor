"""Bioprocess batch-monitoring dashboard.

    streamlit run app.py
"""
from __future__ import annotations

import pandas as pd
import plotly.graph_objects as go
import streamlit as st
from plotly.subplots import make_subplots

from biomon import build, db, monitoring

st.set_page_config(page_title="Bioprocess Monitor", layout="wide")

SOURCES = {
    "indpensim": "IndPenSim (public simulated penicillin fermentation)",
    "synthetic": "SYNTHETIC demo data (generated, with injected faults)",
}
COLORS = {"value": "#2563eb", "band": "rgba(37,99,235,0.12)", "mean": "#64748b",
          "flag": "#f59e0b", "alarm": "#dc2626", "spec": "#9333ea", "missing": "#475569",
          "fault": "rgba(220,38,38,0.08)", "ewma": "#0d9488", "ewma_band": "rgba(13,148,136,0.12)"}


# ---------- data access (cached; each call opens its own SQLite connection) ----------
@st.cache_data
def q(source: str, sql: str, **params) -> pd.DataFrame:
    with db.connect(db.db_path(source)) as conn:
        return db.read_table(conn, sql, **params)


@st.cache_data
def named_query(source: str, name: str, batch_id: str | None = None) -> pd.DataFrame:
    with db.connect(db.db_path(source)) as conn:
        return db.query(conn, name, batch_id=batch_id)


@st.cache_data
def scored_batch(source: str, batch_id: str) -> pd.DataFrame:
    with db.connect(db.db_path(source)) as conn:
        settings = build.settings_from_db(conn)
        readings = db.read_table(conn, "SELECT * FROM readings WHERE batch_id = :b", b=batch_id)
        limits = db.read_table(conn, "SELECT * FROM control_limits")
    return monitoring.evaluate(readings, limits, settings)


# ---------- sidebar ----------
available = [s for s in SOURCES if db.db_path(s).exists()]
if not available:
    st.error("No database found. Run `python -m biomon.build` first (see README).")
    st.stop()

with st.sidebar:
    st.header("Bioprocess Monitor")
    source = st.radio("Dataset", available, format_func=lambda s: SOURCES[s])
    batches = q(source, "SELECT batch_id, role, true_status, notes FROM batches ORDER BY batch_id")
    labels = {r.batch_id: f"{r.batch_id} · {r.role} · {r.true_status}" for r in batches.itertuples()}
    default = batches.index[batches.true_status.eq("fault")].min()
    batch_id = st.selectbox("Batch", batches.batch_id, index=int(default) if pd.notna(default) else 0,
                            format_func=labels.get)
    show_ewma = st.toggle("Show EWMA drift panel", value=True)
    show_spec = st.toggle("Show spec limits", value=True)
    st.caption("Ground truth (normal/fault) is shown for learning purposes; "
               "a real monitoring system would not know it.")

if source == "synthetic":
    st.warning("SYNTHETIC DATA: generated by biomon/synthetic.py to test the methods. Not real process data.")
else:
    st.info("IndPenSim: simulated 100,000 L penicillin fermentation (Goldrick et al., CC BY 4.0). "
            "Agitation is held constant at 100 rpm in this simulator.")

tab_batch, tab_fleet, tab_results = st.tabs(["Batch view", "All batches", "Detection results"])

# ---------- batch view ----------
with tab_batch:
    info = batches.set_index("batch_id").loc[batch_id]
    faults = q(source, "SELECT * FROM faults WHERE batch_id = :b", b=batch_id)
    alarms = q(source, "SELECT * FROM alarms WHERE batch_id = :b ORDER BY start_h", b=batch_id)
    sensors = q(source, "SELECT * FROM sensor_limits")
    cal = q(source, "SELECT method, sensor, calibrated_k FROM calibration")
    k = {(r.method, r.sensor): r.calibrated_k for r in cal.itertuples()}  # per-sensor thresholds

    st.subheader(f"Batch {batch_id}")
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Role", info.role)
    c2.metric("Ground truth", info.true_status)
    c3.metric("Alarm events", len(alarms))
    c4.metric("Missing readings",
              int(named_query(source, "batch_summary", batch_id)["n_missing"].sum()))
    st.caption(f"{info.notes}. Control band: mean ± kσ of baseline batches, with k set per sensor "
               "(shown in each chart title). An alarm = 3+ consecutive flagged points.")
    if len(faults):
        st.markdown("**Known fault(s)** (answer key): " + "; ".join(
            f"{f.kind} on {f.sensor or 'process'} from {f.start_h:g} h to {f.end_h:g} h"
            for f in faults.itertuples()))

    df = scored_batch(source, batch_id)
    for srow in sensors.itertuples():
        d = df[df.sensor == srow.sensor].sort_values("t_hours")
        rows = 2 if show_ewma else 1
        fig = make_subplots(rows=rows, cols=1, shared_xaxes=True, vertical_spacing=0.06,
                            row_heights=[0.7, 0.3][:rows])
        # control band
        fig.add_trace(go.Scatter(x=d.t_hours, y=d.ucl, line=dict(width=0), hoverinfo="skip",
                                 showlegend=False), 1, 1)
        fig.add_trace(go.Scatter(x=d.t_hours, y=d.lcl, fill="tonexty", fillcolor=COLORS["band"],
                                 line=dict(width=0), name="Control band", hoverinfo="skip"), 1, 1)
        fig.add_trace(go.Scatter(x=d.t_hours, y=d["mean"], line=dict(color=COLORS["mean"], dash="dash", width=1),
                                 name="Baseline mean"), 1, 1)
        k_sh = k.get(("shewhart", srow.sensor), 3.0)
        k_ew = k.get(("ewma", srow.sensor), 3.0)
        if k_sh > 3:  # show the textbook band for context when calibration widened it
            for i, sign in enumerate((1, -1)):
                fig.add_trace(go.Scatter(x=d.t_hours, y=d["mean"] + sign * 3 * d["sd"],
                                         line=dict(color=COLORS["mean"], dash="dot", width=1),
                                         name="Textbook ±3σ", showlegend=i == 0, legendgroup="tb"), 1, 1)
        fig.add_trace(go.Scatter(x=d.t_hours, y=d.value, line=dict(color=COLORS["value"], width=1.5),
                                 name="Reading"), 1, 1)
        flag = d[d.shewhart_flag & ~d.shewhart_alarm]
        fig.add_trace(go.Scatter(x=flag.t_hours, y=flag.value, mode="markers", name="Flag (single point)",
                                 marker=dict(color=COLORS["flag"], size=6)), 1, 1)
        alarm = d[d.shewhart_alarm | d.ewma_alarm]
        fig.add_trace(go.Scatter(x=alarm.t_hours, y=alarm.value, mode="markers", name="Alarm",
                                 marker=dict(color=COLORS["alarm"], size=8, symbol="x")), 1, 1)
        # y-axis: fit the readings, spec limits and textbook band, not a very wide calibrated band
        lo = pd.concat([d.value, d["mean"] - 3 * d["sd"]]).min()
        hi = pd.concat([d.value, d["mean"] + 3 * d["sd"]]).max()
        if show_spec:
            lo, hi = min(lo, srow.low if pd.notna(srow.low) else lo), max(hi, srow.high if pd.notna(srow.high) else hi)
        pad = (hi - lo) * 0.08 or 1.0
        fig.update_yaxes(range=[lo - pad, hi + pad], row=1, col=1)
        miss = d[d.missing]
        if len(miss):
            y0 = lo - pad / 2
            fig.add_trace(go.Scatter(x=miss.t_hours, y=[y0] * len(miss), mode="markers", name="Missing reading",
                                     marker=dict(color=COLORS["missing"], symbol="line-ns-open", size=10)), 1, 1)
        if show_spec:
            for lim in (srow.low, srow.high):
                if pd.notna(lim):
                    fig.add_hline(y=lim, line=dict(color=COLORS["spec"], dash="dot", width=1), row=1, col=1)
        if show_ewma:
            fig.add_trace(go.Scatter(x=d.t_hours, y=d.ewma_ucl, line=dict(width=0), hoverinfo="skip",
                                     showlegend=False), 2, 1)
            fig.add_trace(go.Scatter(x=d.t_hours, y=d.ewma_lcl, fill="tonexty", fillcolor=COLORS["ewma_band"],
                                     line=dict(width=0), name="EWMA band", hoverinfo="skip"), 2, 1)
            fig.add_trace(go.Scatter(x=d.t_hours, y=d.ewma, line=dict(color=COLORS["ewma"], width=1.5),
                                     name="EWMA (z units)"), 2, 1)
            e_lo = pd.concat([d.ewma, d.ewma_mean - 3 * d.ewma_sd]).min()
            e_hi = pd.concat([d.ewma, d.ewma_mean + 3 * d.ewma_sd]).max()
            e_pad = (e_hi - e_lo) * 0.1 or 1.0
            fig.update_yaxes(title_text="EWMA", range=[e_lo - e_pad, e_hi + e_pad], row=2, col=1)
        for f in faults.itertuples():
            if f.sensor in (None, srow.sensor) or pd.isna(f.sensor):
                fig.add_vrect(x0=f.start_h, x1=f.end_h, fillcolor=COLORS["fault"], line_width=0)
        fig.update_layout(title=f"{srow.label} ({srow.unit}) · band ±{k_sh:g}σ · EWMA band ±{k_ew:g}σ",
                          height=420 if show_ewma else 320,
                          margin=dict(l=10, r=10, t=40, b=10), hovermode="x unified",
                          legend=dict(orientation="h", y=-0.15))
        fig.update_xaxes(title_text="Hours from batch start", row=rows, col=1)
        st.plotly_chart(fig, width="stretch")

    st.markdown("#### Batch summary (SQL: `sql/batch_summary.sql`)")
    st.dataframe(named_query(source, "batch_summary", batch_id), width="stretch", hide_index=True)
    c1, c2 = st.columns(2)
    with c1:
        st.markdown("#### Alarm events")
        st.dataframe(alarms, width="stretch", hide_index=True)
    with c2:
        st.markdown("#### Missing-reading gaps (SQL: `sql/missing_readings.sql`)")
        st.dataframe(named_query(source, "missing_readings", batch_id), width="stretch", hide_index=True)
    st.markdown("#### Readings outside spec limits (SQL: `sql/out_of_spec.sql`)")
    st.dataframe(named_query(source, "out_of_spec", batch_id), width="stretch", hide_index=True)

# ---------- fleet ----------
with tab_fleet:
    st.markdown("One row per batch (SQL: `sql/fleet_overview.sql`).")
    st.dataframe(named_query(source, "fleet_overview"), width="stretch", hide_index=True)

# ---------- results ----------
with tab_results:
    path = db.ROOT / "reports" / f"detection_{source}.md"
    st.markdown(path.read_text(encoding="utf-8") if path.exists() else "Run `python -m biomon.build` to create the report.")
